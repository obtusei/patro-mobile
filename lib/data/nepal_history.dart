/// Something that happened in Nepal on a given Gregorian month and day.
class HistoryEntry {
  const HistoryEntry(this.month, this.day, this.year, this.text);

  final int month;
  final int day;
  final int year;
  final String text;
}

/// Entries for the AD month and day of [ad], oldest first.
List<HistoryEntry> historyOn(DateTime ad) => [
  for (final e in nepalHistory)
    if (e.month == ad.month && e.day == ad.day) e,
]..sort((a, b) => a.year.compareTo(b.year));

/// A general fact for days with no dated entry; stable for a given date.
String factFor(DateTime ad) {
  final dayOfYear = ad.difference(DateTime.utc(ad.year)).inDays;
  return nepalFacts[dayOfYear % nepalFacts.length];
}

